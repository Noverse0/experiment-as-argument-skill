"""
Entrypoint: generate dataset, run experiment, write results/metrics.json
and REPORT.md.

Usage:
    python3 run_experiment.py [--data churn.csv]
"""
import argparse
import json
import os
import subprocess
import sys
import textwrap

RESULTS_DIR = "results"
METRICS_PATH = os.path.join(RESULTS_DIR, "metrics.json")
REPORT_PATH = "REPORT.md"


def generate_dataset(path: str) -> None:
    print(f"Generating dataset -> {path}")
    subprocess.run(
        [sys.executable, "make_dataset.py", "--out", path],
        check=True,
    )


def write_metrics(results: dict) -> None:
    os.makedirs(RESULTS_DIR, exist_ok=True)
    with open(METRICS_PATH, "w") as f:
        json.dump(results, f, indent=2)
    print(f"Metrics written to {METRICS_PATH}")


def fmt(val: float, decimals: int = 4) -> str:
    return f"{val:.{decimals}f}"


def write_report(results: dict) -> None:
    lr = results["lr"]
    gb = results["gb"]
    sanity = results["sanity"]
    n_seeds = len(results["seeds"])

    # Determine winner by primary metric (ROC-AUC)
    lr_auc = lr["roc_auc"]["mean"]
    gb_auc = gb["roc_auc"]["mean"]
    lr_auc_std = lr["roc_auc"]["std"]
    gb_auc_std = gb["roc_auc"]["std"]

    gap = gb_auc - lr_auc
    # Non-overlap check: intervals [mean±std] are disjoint
    lr_lo, lr_hi = lr_auc - lr_auc_std, lr_auc + lr_auc_std
    gb_lo, gb_hi = gb_auc - gb_auc_std, gb_auc + gb_auc_std
    intervals_overlap = gb_lo <= lr_hi and lr_lo <= gb_hi

    if abs(gap) < 0.005 or intervals_overlap:
        conclusion = (
            "**No detectable difference.** The gap between GradientBoosting and "
            "LogisticRegression falls within the noise of repeated runs. "
            "Neither model can be declared the winner from this evidence."
        )
    elif gap > 0:
        conclusion = (
            f"**GradientBoosting outperforms LogisticRegression** on ROC-AUC "
            f"(Δ = {gap:.4f}), with non-overlapping ±1 std spreads across {n_seeds} seeds."
        )
    else:
        conclusion = (
            f"**LogisticRegression outperforms GradientBoosting** on ROC-AUC "
            f"(Δ = {-gap:.4f}), with non-overlapping ±1 std spreads across {n_seeds} seeds."
        )

    # Sanity check summary
    all_passed = all([
        sanity["overfit_lr"]["passed"],
        sanity["overfit_gb"]["passed"],
        sanity["label_shuffle_lr"]["passed"],
        sanity["label_shuffle_gb"]["passed"],
    ])
    sanity_status = "PASSED" if all_passed else "FAILED (see details below)"

    report = textwrap.dedent(f"""\
    # Churn Prediction Experiment: GB vs Logistic Regression

    ## Claim

    Does gradient boosting outperform logistic regression for predicting customer
    churn on this dataset?

    ## Methodology

    **Dataset:** {results['n_raw']} rows generated by `make_dataset.py`.

    **Deduplication:** {results['n_duplicates_removed']} exact duplicate rows removed
    before splitting ({results['n_after_dedup']} rows remain).

    **Leakage removed:** `account_status` was dropped because it is a direct encoding
    of the target (`"closed"` iff `churned=1`). Including it would be perfect label
    leakage. `customer_id` was dropped as an opaque identifier.

    **Features used:** `tenure_months`, `monthly_spend`, `support_tickets`,
    `days_since_start` (days since earliest signup date in the dataset).

    **Split:** Temporal — rows sorted by `signup_date`; earliest 80 % form the
    training set, latest 20 % the test set ({results['n_train']} train /
    {results['n_test']} test). This mirrors real deployment: train on historical
    customers, predict for newly acquired ones. A random split would be inappropriate
    given the temporal column.

    **Preprocessing:** `StandardScaler` fitted on the training set only; applied
    to the test set without refitting.

    **Primary metric:** ROC-AUC (robust to class imbalance; target rate train =
    {sanity['baseline']['target_rate_train']:.3f}, test =
    {sanity['baseline']['target_rate_test']:.3f}).

    **Seeds:** {n_seeds} random seeds ({results['seeds']}). `LogisticRegression`
    (lbfgs solver) is deterministic given fixed data, so its std is 0. Variance
    is meaningful for `GradientBoostingClassifier`.

    ## Sanity Checks — {sanity_status}

    | Check | Result |
    |-------|--------|
    | Majority-class accuracy (baseline floor) | {sanity['baseline']['majority_class_accuracy']:.4f} |
    | Overfit tiny subset — LR | accuracy = {sanity['overfit_lr']['accuracy_on_tiny']:.4f} ({'PASS' if sanity['overfit_lr']['passed'] else 'FAIL'}) |
    | Overfit tiny subset — GB | accuracy = {sanity['overfit_gb']['accuracy_on_tiny']:.4f} ({'PASS' if sanity['overfit_gb']['passed'] else 'FAIL'}) |
    | Label-shuffle mean AUC — LR | {sanity['label_shuffle_lr']['mean_auc_with_shuffled_labels']:.4f} ({'PASS' if sanity['label_shuffle_lr']['passed'] else 'FAIL'}) |
    | Label-shuffle mean AUC — GB | {sanity['label_shuffle_gb']['mean_auc_with_shuffled_labels']:.4f} ({'PASS' if sanity['label_shuffle_gb']['passed'] else 'FAIL'}) |

    ## Results (mean ± std over {n_seeds} seeds)

    | Metric | LogisticRegression | GradientBoosting |
    |--------|--------------------|-----------------|
    | ROC-AUC ↑ | {lr_auc:.4f} ± {lr_auc_std:.4f} | {gb_auc:.4f} ± {gb_auc_std:.4f} |
    | F1 ↑ | {lr['f1']['mean']:.4f} ± {lr['f1']['std']:.4f} | {gb['f1']['mean']:.4f} ± {gb['f1']['std']:.4f} |
    | Precision ↑ | {lr['precision']['mean']:.4f} ± {lr['precision']['std']:.4f} | {gb['precision']['mean']:.4f} ± {gb['precision']['std']:.4f} |
    | Recall ↑ | {lr['recall']['mean']:.4f} ± {lr['recall']['std']:.4f} | {gb['recall']['mean']:.4f} ± {gb['recall']['std']:.4f} |
    | Brier ↓ | {lr['brier']['mean']:.4f} ± {lr['brier']['std']:.4f} | {gb['brier']['mean']:.4f} ± {gb['brier']['std']:.4f} |

    ## Conclusion

    {conclusion}

    ## Limitations and Validity Threats

    - **Single temporal split:** variance estimates come from model randomness only, not
      from split variation. A walk-forward or expanding-window evaluation would give a
      more robust estimate of out-of-time generalisation.
    - **No hyperparameter tuning:** both models use default/fixed hyperparameters. A
      tuned GB may widen the gap; a tuned LR may close it.
    - **Synthetic data:** the true data-generating process is logistic with three
      additive features. LR is the correct model class; any GB advantage reflects
      overfitting, not a genuine signal advantage.
    - **{n_seeds} seeds:** sufficient to detect gross differences, but formal statistical
      testing (e.g., paired t-test across CV folds) would be needed for a publication-
      level claim.
    - **`days_since_start` is not predictive** in the generating process (it does not
      appear in the logit formula). Its inclusion does not add signal but also does
      not harm; it was retained to honour the temporal split rationale.
    """)

    with open(REPORT_PATH, "w") as f:
        f.write(report)
    print(f"Report written to {REPORT_PATH}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", default="churn.csv", help="Path to churn CSV")
    args = parser.parse_args()

    if not os.path.exists(args.data):
        generate_dataset(args.data)

    from src.experiment import run
    print("Running experiment...")
    results = run(args.data)

    # Print summary to stdout
    print(f"\nDuplicates removed: {results['n_duplicates_removed']}")
    print(f"Train / Test: {results['n_train']} / {results['n_test']}")
    print(f"\nSanity checks:")
    for k, v in results["sanity"].items():
        print(f"  {k}: {v}")
    print(f"\nLR  ROC-AUC: {results['lr']['roc_auc']['mean']:.4f} ± {results['lr']['roc_auc']['std']:.4f}")
    print(f"GB  ROC-AUC: {results['gb']['roc_auc']['mean']:.4f} ± {results['gb']['roc_auc']['std']:.4f}")

    write_metrics(results)
    write_report(results)


if __name__ == "__main__":
    main()
