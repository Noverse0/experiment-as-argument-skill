"""Entrypoint: run full churn prediction experiment and write results + report."""
import json
import os
import subprocess
import sys
from pathlib import Path

from src.data import get_features_target, load_data, temporal_split
from src.evaluate import cv_metrics, holdout_metrics
from src.pipeline import make_gb_pipeline, make_lr_pipeline

SEED = 42
CV_SPLITS = 5
TRAIN_FRAC = 0.8


def _generate_dataset() -> None:
    subprocess.run(
        [sys.executable, "make_dataset.py", "--out", "churn.csv"],
        check=True,
    )


def _write_report(results: dict, meta: dict) -> None:
    lr = results["LogisticRegression"]
    gb = results["GradientBoosting"]

    lr_cv_mean = lr["cv"]["roc_auc"]["mean"]
    lr_cv_std = lr["cv"]["roc_auc"]["std"]
    gb_cv_mean = gb["cv"]["roc_auc"]["mean"]
    gb_cv_std = gb["cv"]["roc_auc"]["std"]

    cv_gap = gb_cv_mean - lr_cv_mean
    noise_threshold = max(lr_cv_std, gb_cv_std)

    if abs(cv_gap) < noise_threshold:
        conclusion = (
            "**No detectable difference.** "
            f"The CV ROC-AUC gap ({cv_gap:+.3f}) is smaller than the per-model "
            f"fold-to-fold noise (threshold: {noise_threshold:.3f}), "
            "so neither model is the clear winner on this dataset."
        )
    elif cv_gap > 0:
        conclusion = (
            f"**GradientBoosting outperforms LogisticRegression** "
            f"(CV ROC-AUC gap {cv_gap:+.3f} > noise threshold {noise_threshold:.3f})."
        )
    else:
        conclusion = (
            f"**LogisticRegression outperforms GradientBoosting** "
            f"(CV ROC-AUC gap {cv_gap:+.3f}, magnitude > noise threshold {noise_threshold:.3f})."
        )

    lr_test_auc = lr["test"]["roc_auc"]
    gb_test_auc = gb["test"]["roc_auc"]
    test_gap = gb_test_auc - lr_test_auc

    report = f"""# Churn Prediction: Gradient Boosting vs Logistic Regression

## Claim

Does GradientBoostingClassifier outperform LogisticRegression for predicting customer churn on this dataset?

## Methodology

### Data Preparation

- **Raw rows**: {meta["n_raw"]} → removed {meta["n_dupes"]} exact duplicates → **{meta["n_clean"]} unique rows**
- **Dropped `account_status`**: this column encodes the target perfectly (`"closed"` iff `churned=1`); retaining it would be label leakage.
- **Dropped `customer_id`**: identifier, not a predictive feature.
- **`signup_date` → `days_since_start`**: converted to integer days since the earliest signup to preserve its ordinal signal while making it numeric.
- **Temporal split**: rows sorted by `days_since_start`; first {int(TRAIN_FRAC*100)}% → train ({meta["n_train"]} rows), last {100-int(TRAIN_FRAC*100)}% → test ({meta["n_test"]} rows). The test set is **touched once** at the very end.
- **Churn rate**: {meta["churn_rate"]:.3f} ({meta["churn_rate"]*100:.1f}%)

### Features

`tenure_months`, `monthly_spend`, `support_tickets`, `days_since_start`
(StandardScaler fitted **on train only**, applied to train and test separately)

### Evaluation Protocol

- **Cross-validation**: `TimeSeriesSplit(n_splits={CV_SPLITS})` on the training set to estimate variance without touching the test set.
- **Primary metric**: ROC-AUC — robust to class imbalance and threshold choice.
- **Secondary metrics**: F1, Precision, Recall (at default 0.5 threshold).
- **Models**: default hyperparameters, `random_state={SEED}` for both.
- **Conclusion criterion**: gap is "detectable" only if `|CV mean gap| > max(LR std, GB std)`.

## Results

### Cross-Validation (TimeSeriesSplit, {CV_SPLITS} folds, train set only)

| Model | ROC-AUC | F1 |
|---|---|---|
| LogisticRegression | {lr_cv_mean:.3f} ± {lr_cv_std:.3f} | {lr["cv"]["f1"]["mean"]:.3f} ± {lr["cv"]["f1"]["std"]:.3f} |
| GradientBoosting   | {gb_cv_mean:.3f} ± {gb_cv_std:.3f} | {gb["cv"]["f1"]["mean"]:.3f} ± {gb["cv"]["f1"]["std"]:.3f} |

CV fold scores (ROC-AUC):
- LR: {[round(s, 3) for s in lr["cv"]["roc_auc"]["scores"]]}
- GB: {[round(s, 3) for s in gb["cv"]["roc_auc"]["scores"]]}

### Hold-Out Test Set (touched once)

| Model | ROC-AUC | F1 | Precision | Recall |
|---|---|---|---|---|
| LogisticRegression | {lr_test_auc:.3f} | {lr["test"]["f1"]:.3f} | {lr["test"]["precision"]:.3f} | {lr["test"]["recall"]:.3f} |
| GradientBoosting   | {gb_test_auc:.3f} | {gb["test"]["f1"]:.3f} | {gb["test"]["precision"]:.3f} | {gb["test"]["recall"]:.3f} |

Test ROC-AUC gap (GB − LR): {test_gap:+.3f}

## Conclusion

{conclusion}

## Limitations

1. **Synthetic data / known DGP**: the dataset was generated by a logistic model, which structurally favors LogisticRegression. Real churn data may behave differently.
2. **No hyperparameter tuning**: default parameters were used for both models. GradientBoosting may have larger upside with tuning.
3. **Single seed**: variance across model random initializations is not measured.
4. **TimeSeriesSplit growing-train-set effect**: early folds train on smaller data, which may understate the final performance.
5. **days_since_start as split proxy**: we use signup date as a proxy for temporal ordering; the actual event date of churn is not recorded.
"""

    Path("REPORT.md").write_text(report)


def main() -> None:
    if not Path("churn.csv").exists():
        print("Generating dataset...")
        _generate_dataset()

    print("Loading and preparing data...")
    df, n_dupes = load_data("churn.csv")
    n_raw = len(df) + n_dupes
    print(f"  {n_raw} rows raw → {len(df)} after removing {n_dupes} duplicates")
    print(f"  Churn rate: {df['churned'].mean():.3f}")

    train_df, test_df = temporal_split(df, train_frac=TRAIN_FRAC)
    X_train, y_train = get_features_target(train_df)
    X_test, y_test = get_features_target(test_df)
    print(f"  Train: {len(X_train)}  Test: {len(X_test)}")

    models = {
        "LogisticRegression": make_lr_pipeline(SEED),
        "GradientBoosting": make_gb_pipeline(SEED),
    }

    results: dict = {}

    print(f"\nCross-validation (TimeSeriesSplit, {CV_SPLITS} folds)...")
    for name, pipe in models.items():
        print(f"  {name}...", end=" ", flush=True)
        cv = cv_metrics(pipe, X_train, y_train, n_splits=CV_SPLITS)
        results[name] = {"cv": cv}
        print(f"ROC-AUC {cv['roc_auc']['mean']:.3f} ± {cv['roc_auc']['std']:.3f}")

    print("\nFinal evaluation on held-out test set (once)...")
    for name, pipe in models.items():
        print(f"  {name}...", end=" ", flush=True)
        test = holdout_metrics(pipe, X_train, y_train, X_test, y_test)
        results[name]["test"] = test
        print(f"ROC-AUC {test['roc_auc']:.3f}")

    os.makedirs("results", exist_ok=True)
    with open("results/metrics.json", "w") as f:
        json.dump(results, f, indent=2)

    meta = {
        "n_raw": n_raw,
        "n_dupes": n_dupes,
        "n_clean": len(df),
        "n_train": len(X_train),
        "n_test": len(X_test),
        "churn_rate": float(df["churned"].mean()),
    }
    with open("results/meta.json", "w") as f:
        json.dump(meta, f, indent=2)

    _write_report(results, meta)
    print("\nWrote results/metrics.json, results/meta.json, REPORT.md")


if __name__ == "__main__":
    main()
