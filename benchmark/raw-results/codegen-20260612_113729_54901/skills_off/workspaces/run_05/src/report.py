"""Generate REPORT.md from experiment results."""


def write_report(results: dict, path: str) -> None:
    d = results
    di = d["data_info"]
    sc = d["sanity_checks"]
    lr = d["logistic_regression"]
    gb = d["gradient_boosting"]
    seeds = d["seeds"]

    lr_auc = lr["roc_auc"]
    gb_auc = gb["roc_auc"]
    lr_ap = lr["avg_precision"]
    gb_ap = gb["avg_precision"]

    auc_gap = gb_auc["mean"] - lr_auc["mean"]
    ap_gap = gb_ap["mean"] - lr_ap["mean"]

    # Overlap check: do the spreads share territory?
    lr_auc_lo = lr_auc["mean"] - lr_auc["std"]
    gb_auc_hi = gb_auc["mean"] + gb_auc["std"]
    gb_auc_lo = gb_auc["mean"] - gb_auc["std"]
    lr_auc_hi = lr_auc["mean"] + lr_auc["std"]
    spreads_overlap = lr_auc_lo < gb_auc_hi and gb_auc_lo < lr_auc_hi

    if abs(auc_gap) < 0.01 or spreads_overlap:
        conclusion = (
            "**No detectable difference.** "
            "The ROC-AUC gap between the two models is within the noise of this experiment "
            "(gap < 0.01 or spreads overlap). Neither model can be declared the winner "
            "without more runs, a larger dataset, or a statistical test."
        )
    elif auc_gap > 0:
        conclusion = (
            f"**Gradient Boosting appears stronger** by {auc_gap:+.4f} ROC-AUC "
            f"({gb_auc['mean']:.4f} vs {lr_auc['mean']:.4f}), "
            f"but the spread across {len(seeds)} seeds should be inspected before "
            "claiming a definitive win."
        )
    else:
        conclusion = (
            f"**Logistic Regression appears stronger** by {abs(auc_gap):.4f} ROC-AUC "
            f"({lr_auc['mean']:.4f} vs {gb_auc['mean']:.4f}). "
            "This is a surprising result on a dataset generated by a logistic process, "
            "suggesting GB may be overfitting the training set."
        )

    shuffle_ok = sc["label_shuffle_near_chance"]
    # Leakage would show as AUC above chance; below is fine.
    shuffle_flag = "PASS (no leakage signal)" if shuffle_ok else "FAIL — AUC above chance with shuffled labels"

    lines = [
        "# Churn Prediction Experiment Report",
        "",
        "## Claim",
        "Does gradient boosting outperform logistic regression for predicting customer churn?",
        "",
        "## Design",
        "",
        f"- **Variable:** model family (LogisticRegression vs GradientBoostingClassifier)",
        f"- **Dataset:** {di['n_before_dedup']} rows; {di['n_dupes_removed']} exact duplicates removed "
        f"before splitting ({di['n_after_dedup']} unique rows retained)",
        f"- **Split policy:** time-based (sort by `signup_date`, first 70% → train, last 30% → test). "
        "Random splits were rejected because `signup_date` is temporal.",
        f"- **Train / test size:** {di['n_train']} / {di['n_test']} rows",
        f"- **Target rate:** {di['target_rate_train']:.1%} churn in train, "
        f"{di['target_rate_test']:.1%} in test",
        f"- **Seeds × repeats:** {len(seeds)} seeds ({seeds})",
        "- **Preprocessing:**",
        "  - Dropped `account_status` — it directly encodes the target (perfect leak).",
        "  - Dropped `customer_id` — non-predictive identifier.",
        "  - `StandardScaler` fit on train only, applied to test (LR uses scaled features; "
        "GB uses raw features — tree models are scale-invariant).",
        "- **Features used:** `tenure_months`, `monthly_spend`, `support_tickets`, `signup_ordinal`",
        "- **Primary metric:** ROC-AUC (threshold-free, handles class imbalance)",
        "- **Secondary metric:** Average Precision (area under PR curve; more informative "
        "when positives are the minority class)",
        "",
        "## Sanity Checks",
        "",
        f"| Check | Value | Status |",
        f"|-------|-------|--------|",
        f"| Majority-class baseline ROC-AUC | {sc['baseline_majority_roc_auc']:.4f} | reference floor |",
        f"| Majority-class baseline Avg Precision | {sc['baseline_majority_avg_precision']:.4f} | reference floor |",
        f"| Label-shuffle ROC-AUC (LR probe) | {sc['label_shuffle_roc_auc']:.4f} | {shuffle_flag} |",
        "",
        "Both models must beat the majority-class baseline. "
        "The label-shuffle AUC must be near 0.5 (chance) — "
        "a value materially above chance would indicate information leaking around the labels.",
        "",
        "## Results",
        "",
        "### ROC-AUC",
        "",
        f"| Model | Mean | Std | n |",
        f"|-------|------|-----|---|",
        f"| Logistic Regression | {lr_auc['mean']:.4f} | {lr_auc['std']:.4f} | {lr_auc['n']} |",
        f"| Gradient Boosting   | {gb_auc['mean']:.4f} | {gb_auc['std']:.4f} | {gb_auc['n']} |",
        f"| Majority baseline   | {sc['baseline_majority_roc_auc']:.4f} | — | — |",
        "",
        "### Average Precision",
        "",
        f"| Model | Mean | Std | n |",
        f"|-------|------|-----|---|",
        f"| Logistic Regression | {lr_ap['mean']:.4f} | {lr_ap['std']:.4f} | {lr_ap['n']} |",
        f"| Gradient Boosting   | {gb_ap['mean']:.4f} | {gb_ap['std']:.4f} | {gb_ap['n']} |",
        f"| Majority baseline   | {sc['baseline_majority_avg_precision']:.4f} | — | — |",
        "",
        "### Conclusion",
        "",
        conclusion,
        "",
        f"AUC gap (GB − LR): {auc_gap:+.4f}  ",
        f"AP gap (GB − LR): {ap_gap:+.4f}",
        "",
        "## Limitations and Remaining Risks",
        "",
        "- **Single temporal split:** the 70/30 cut is one point in time. "
        "A walk-forward cross-validation would give a more stable estimate of generalization.",
        "- **No hyperparameter tuning:** both models use defaults (except `subsample=0.8` for GB). "
        "A fair comparison would tune both arms with equal budget on the training set.",
        "- **5 seeds only:** the spread reported here is indicative, not a rigorous "
        "statistical test. With near-zero std, a formal test would add little; "
        "with non-trivial spread, a paired t-test or Wilcoxon test on held-out fold scores "
        "would be needed before claiming a winner.",
        "- **Synthetic data:** this dataset was generated by a logistic model, "
        "which inherently favors logistic regression. On real churn data the relative "
        "performance could differ.",
        "- **`signup_ordinal` feature:** encoding the date as days-since-epoch is a "
        "simplification; in production, recency relative to the prediction date would "
        "be more meaningful.",
    ]

    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
